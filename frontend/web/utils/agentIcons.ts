/**
 * 稳定哈希函数（djb2 变体）
 *
 * 输入字符串，输出 32 位无符号整数。
 * 同一字符串始终返回同一数值，确保 agentId → iconPath 的匹配稳定。
 */
function hashAgentId(agentId: string): number {
  let hash = 5381
  for (let i = 0; i < agentId.length; i++) {
    // hash * 33 + charCode，通过位运算加速
    hash = ((hash << 5) + hash) + agentId.charCodeAt(i)
    // 限制为 32 位无符号整数，避免 JS 位运算出现负数
    hash = hash & 0xffffffff
  }
  // 取绝对值，避免负数影响取模
  return Math.abs(hash)
}

/**
 * 根据 agent_id 稳定匹配一个图标 path
 *
 * - 同一 agent_id 永远返回同一个 path（视觉记忆稳定）
 * - 不同 agent_id 在 200 个图标中均匀分布（少量碰撞可接受）
 * - 空 agent_id 回退到第一个图标作为兜底
 *
 * @param agentId 数字员工的 agent_id
 * @returns SVG path 的 d 字符串
 */
export function getAgentIconPath(agentId: string): string {
  if (!agentId) return AGENT_ICON_PATHS[0]
  return AGENT_ICON_PATHS[hashAgentId(agentId) % AGENT_ICON_PATHS.length]
}
