#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""行程文本解析 - LLM 提取景点/团队/路线"""

import json
import re
from typing import Any, Dict

from loguru import logger

from llm_client import call_llm


def _llm_kwargs(task: str, max_tokens: int, timeout: float = 60.0) -> Dict[str, Any]:
    kwargs: Dict[str, Any] = {
        "timeout": timeout,
        "max_tokens": max_tokens,
        "task": task,
    }
    try:
        from src.config.settings import settings
        if settings.llm.provider == "deepseek":
            kwargs["extra_body"] = {"thinking": {"type": "disabled"}}
    except Exception:
        pass
    return kwargs


def parse_itinerary(itinerary_text: str) -> dict:
    """调用 LLM 从行程文本中提取报价所需的参数"""
    prompt = f"""你是一个旅游行程解析助手。请从以下行程方案文本中提取报价所需的关键信息。

行程方案：
{itinerary_text}

请返回 JSON 格式，包含以下字段：
{{
    "region_name": "主要目的地（省份或城市名）",
    "total_people": 30,
    "adults": 0,
    "children_half": 0,
    "students": 30,
    "elders": 0,
    "couples": 0,
    "teacher_count": 3,
    "trip_days": 4,
    "departure_city": "出发城市",
    "destination": "行程的主要目的地城市（最远或停留最久的那个城市名，不带市/县后缀，单一名）",
    "daily_attractions": [
        {{
            "day": 1,
            "attractions": [
                {{"name": "平塘天文小镇", "activities": ["开营仪式"]}}
            ]
        }},
        {{
            "day": 2,
            "attractions": [
                {{"name": "天眼景区", "activities": ["FAST观景台参观", "天文科普讲座"]}},
                {{"name": "南仁东纪念馆", "activities": []}}
            ]
        }},
        {{
            "day": 3,
            "attractions": [
                {{"name": "小七孔景区", "activities": ["卧龙潭", "翠谷瀑布"]}}
            ]
        }}
    ],
    "hotel_preference": "4钻酒店",
    "hotel_stays": [
        {{"city": "贵阳", "area": "南明区", "nights": 2, "room_type": ""}},
        {{"city": "安顺", "area": "西秀区", "nights": 1, "room_type": "大床房"}}
    ],
    "daily_routes": [
        {{
            "day": 1,
            "legs": [
                {{"from": "贵阳市区", "to": "平塘天文小镇"}},
                {{"from": "平塘天文小镇", "to": "平塘酒店"}}
            ]
        }},
        {{
            "day": 2,
            "legs": [
                {{"from": "平塘酒店", "to": "天眼景区"}},
                {{"from": "天眼景区", "to": "南仁东纪念馆"}},
                {{"from": "南仁东纪念馆", "to": "平塘酒店"}}
            ]
        }}
    ],
    "meal_tier": "standard",
    "guide_type": "local"
}}

注意：
1. **人数分配规则（必须严格遵守）**：
   - total_people = adults + children_half + students + elders（不含 teacher_count）
   - adults = 普通成人游客（非学生、非儿童、非老人），按成人票计费
   - students = 学生群体（初中生、高中生、大学生等），按学生票计费
   - children_half = 需要购买儿童半票的儿童人数
   - elders = 老人人数
   - teacher_count = 随队老师/领队人数，老师**不计入** adults 和 students，是独立字段
   - **关键**：如果行程明确说"XX名学生"或"XX名初一/初三/高一学生"，这些全是 students，不是 adults。adults 应为 0
   - **关键**：students + adults + children_half + elders 必须等于 total_people（不含 teacher_count）。如果30人中全部是学生且没提其他成人，则 students=30, adults=0
   - **关键**：老师不要放入 adults 中！如果文本说"30人初三学生+3名老师"，total_people=30, students=30, adults=0, teacher_count=3
2. daily_attractions 从每天行程中提取当天要去的景点和具体游玩项目。name 是景点名称。activities 是该景点中计划体验的具体项目/活动名称。**只填入明确计入费用的项目**，规则如下：
   - **【原样复制，不要改写】**：activities 的字符串**必须原样复制行程文本"游玩项目"列中的项目名**，不要拼接、改写、加修饰词。例如行程写"卧龙潭"，就填 `"卧龙潭"`，不要写成"卧龙潭观光游览"或"卧龙潭参观"
   - **【每项一个活动】**：行程"游玩项目"列如果用顿号（、）、中文逗号（，）、英文逗号（,）、空格分隔了多个活动，**必须拆分成多个 activities 项**，每项一个活动名。例如：
     - 行程写 `"卧龙潭、翠谷瀑布"` → activities 填 `["卧龙潭", "翠谷瀑布"]`
     - 行程写 `"丛林探险、丛林飞跃"` → activities 填 `["丛林探险", "丛林飞跃"]`
     - ❌ 错误：`["卧龙潭、翠谷瀑布"]`（合并成一项）
   - **【可选项目不计入】**：如果行程文本中该项目带有以下字样之一，**不要**写入 activities，仅视为备注信息：`可选`、`自由活动`、`自理`、`或`（如"自由活动或水葩水寨"）、`建议`、`另行付费`、`自费`
   - **【必须计入】**：行程明确写"含"、"已含"、"安排"、"体验"、"课程"、"讲解"的项目，且不带上面这些字样，写入 activities
   - **【编造禁止】**：行程只提到参观景点没提具体项目时（"游玩项目"列为空或"—"），activities 填空数组[]。不要编造行程中未提到的项目，不要把行程安排描述（如"团队建设"、"开营仪式"）当作收费项目除非行程明确将其列为游玩项目
   - **【营地/酒店活动不当作景区】**：如果行程文本明确写"入住 XX 营地"、"入住 XX 酒店"，随后在酒店/营地内做的活动（如"开营仪式"、"团队建设"、"结营仪式"），**不要**当作景区景点（既不算 attraction 也不算 activities），因为这些通常没有门票或单独计费
   - **【同一景区的子场馆合并为一个景点】**：**同一天**出现的同一景区的多个子场馆（如"天文体验馆"、"南仁东事迹馆"、"FAST观景台"都属于"中国天眼科普基地"），合并为一个景点，name 用主景区名（如"中国天眼科普基地"），子场馆的项目合并到 activities
   - **【不同天的同景区分开记录】**：如果**不同天**都去了同一个景区（如 D1 和 D2 都在"中国天眼科普基地"），**必须按天分别记录为独立的 day 条目**，每条 attractions 中只包含当天在该景区实际产生的活动。**不要把不同天的同景区合并到一个 day 条目里**（即使 name 相同，也应分开成两个 day）
     - ✅ 正确：每天单独一条 day 记录，name 相同但 day 不同
     - ❌ 错误：把 D1 和 D2 同景区合并到一个 day 条目里
   - **【晚间活动归入当日景区】**：晚上在景区营地或附近做的活动（如"天文小课堂"、"夜游望远镜观星"），归入该景区的 activities（前提是该活动在"游玩项目"列明确列出）
   - **【不同景区的同一天】**：如果同一天确实去了多个独立景区（距离较远），则分别列出
   - **【引号处理】**：复制项目名时，如果行程原文里项目名被中文引号 `"…"` 或英文引号 `"…"` 包裹，**复制时去掉引号**。例如行程写 `"贵州桥语"项目化课程`，activities 填 `贵州桥语项目化课程`
   - **【输出前自检】**：输出前确认：
     1) daily_attractions 中不存在同一景区的重复条目
     2) 每项 activities 的字符串都来源于行程文本，无编造或改写
     3) 同一格中顿号分隔的多活动已拆分成多项
     4) 项目名无引号包裹
     5) 没有景点项的天，**不要输出空 attractions 的 day 条目**（直接跳过该天，不输出）
3. hotel_preference 是酒店偏好描述（如"4钻"、"经济型"、"标准"），不是酒店名。如果行程未明确提酒店等级，填"标准"
4. hotel_stays 从每天的行程安排中提取：看每天住哪个城市，同一城市连续几晚合并为一项。nights 总和应等于 trip_days - 1。
   - **city 统一不带"县/市"后缀**：city 字段填城市/县城的简短名，不带"县"、"市"、"区"等行政后缀（例如填"平塘"而非"平塘县"，填"贵阳"而非"贵阳市"）。**这是为了与酒店知识库的城市字段命名保持一致，避免检索失配**
   - area 是酒店所在区/县，如果无法确定具体区县则为空字符串
   - **room_type** 是客户/行程指定的房型关键词，**可选字段，默认空字符串 ""**（注意：不是 hotel_preference，hotel_preference 是酒店等级如"4钻"）。
     何时填入房型：
     - 行程"住宿"列、"备注"列、客户对话中**明确写了房型**时填入，例如"大床房"、"亲子房"、"套房"、"双床房"、"标准间"、"家庭房"
     - 去掉修饰词保留核心房型名：行程写"豪华大床房"→填"大床房"；行程明确写"豪华大床房"且无明显核心词时原样填
     - 同一城市多晚住同一酒店但房型不同时，按主要房型填一个（取首晚或最频繁出现的）
     何时填空字符串 ""：
     - 行程只写"入住 XX 酒店"未提房型
     - 行程只写"4 钻/5 星/经济型/高档型"等**酒店等级**（这些归 hotel_preference，不是 room_type）
     - 行程完全没提任何房型信息
     **不要编造**：未明确提到房型时一律填 ""，不要根据酒店星级脑补房型
5. teacher_count 是随队老师人数，如果文本没提，默认 0
6. meal_tier 和 guide_type 如果文本没提，用默认值 standard 和 local
7. **daily_routes（用车段提取，必须严格按以下规则，避免重复报价漂移）**：
   - **【跨城判定 — 关键词组合】**：以下任一关键词组合出现时，**必须提取该段**（即使当天还有别的活动）：
     - "乘车前往" / "前往" / "抵达" + 另一城市名（如"乘车前往荔波"）
     - "约 X 小时车程" / "约 X km" / "X 公里"（如"约3小时车程"）
     - 接站日的"接站"、送站日的"送站"
   - **【⚠️ 不要因为当天有市内活动就漏掉跨城段】**：即使同一天上午在 A 城市景区、下午才"乘车前往 B 城市"，**A城市→B城市 这一段必须提取**。常见的漏提场景：
     - ✅ 必须提取：D1 上午 黔灵山公园 → D1 下午 乘车前往荔波（约3小时），legs 中必须有一段 from="贵阳" to="荔波"
     - ✅ 必须提取：D3 傍晚 乘车返回贵阳（约3小时车程），legs 中必须有一段 from="荔波" to="贵阳"
     - ❌ 错误：因为 D1 上午在黔灵山公园、下午才出发，就漏掉 贵阳→荔波 这段
   - **【不提取以下段】**（即使文本中提到了景点间移动）：
     - 同一天内的酒店↔景区往返（视为景区内活动，避免坐标漂移）
     - 同一景区内多个子场馆之间的移动（如"天文体验馆→南仁东事迹馆"）
     - 只写"入住"、"自由活动"、"休息"、"晚饭"的段
     - from == to 的段
   - **【POI 归一为城市/区县名】**：`from` 和 `to` **必须使用城市名或区县名**，不要用景区内具体 POI。理由：高德 API 对景区内具体 POI（如"天眼景区"、"FAST观景台"）回波坐标不稳定，会引入里程方差。
     - ✅ 正确：`"from": "贵阳", "to": "平塘县"`
     - ✅ 正确：`"from": "平塘县", "to": "荔波县"`
     - ❌ 错误：`"from": "平塘酒店", "to": "天眼景区"`（同一天往返，不提取）
     - ❌ 错误：`"from": "中国天眼科普基地", "to": "南仁东事迹馆"`（景区内子场馆，不提取）
   - **【输出前自检】**：扫描行程文本中所有出现的"乘车前往"、"约 X 小时车程"、"X 公里"、"返回 X"、"接站"、"送站"，每一个都应该对应 daily_routes 中的至少一段。如果有跨城关键词但 daily_routes 里没对应段，必须补上
   - **【天数对齐】**：daily_routes 的长度等于 trip_days，没车的天 legs 为空数组 []
   - **【示例】**：6天5晚行程，D1 贵阳→平塘、D3 平塘→荔波、D6 荔波→贵阳，则只有 D1/D3/D6 各 1 段，D2/D4/D5 legs 为空数组
8. **关闭推理模式下的硬性自检（必须执行）**：
   - daily_attractions 要列出所有实际游览的收费/景区景点，即使"游玩项目"列是 "—" 或空，也要输出该景点并让 activities=[]。例如 "天龙屯堡 | —" 必须输出 {{"name":"天龙屯堡","activities":[]}}
   - 不要因为 activities 为空就删除景点；只删除纯酒店/自由活动/用餐/车程而非景点的天
   - activities 必须逐字复制"游玩项目"列，保留括号、中文标点和补充说明。例如 "扶梯（单程）" 必须原样输出，不能简化为 "扶梯"
   - 景点 name 优先使用行程安排中的主景点名；不要把小七孔改成大七孔，不要随意换同义景点
9. 只返回 JSON，不要其他文字"""

    raw = call_llm(
        prompt,
        **_llm_kwargs("itinerary_parse", max_tokens=4096),
    )

    json_match = re.search(r'```(?:json)?\s*(\{.*?\})\s*```', raw, re.DOTALL)
    if json_match:
        raw = json_match.group(1)
    return json.loads(raw.strip())
